"""Generate firmware-default preset table from editable seed CSV.

Run only if changing factory defaults in source. Actual user edits are saved in LittleFS.
"""
import csv, json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
rows=list(csv.DictReader((root/'stations.csv').open(encoding='utf-8-sig', newline='')))
assert len(rows) == 20, f'Expected 20 presets, got {len(rows)}'
assert len(set(r['url'] for r in rows)) == 20, 'Duplicate station stream URLs'
assert rows[0]['name']=='181.FM 90s Alternative'
lines=['// Generated from stations.csv — 20 editable initial station presets.',
       '// Do not edit this file manually. Edit stations.csv and run scripts/generate_defaults.py.',
       '#pragma once',
       'struct DefaultStation { const char* name; const char* genre; const char* url; };',
       'static constexpr DefaultStation kDefaultStations[20] = {']
for r in rows:
    lines.append('  {' + ', '.join(json.dumps(r[k],ensure_ascii=True) for k in ['name','genre','url']) + '},')
lines+=['};','static_assert(sizeof(kDefaultStations)/sizeof(kDefaultStations[0]) == 20, "20 presets required");']
(root/'src'/'default_stations.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated',len(rows),'presets')
